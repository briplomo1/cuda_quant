"""Turns the logs from scripts/run_experiments.sh into the report's tables and plots.

  python scripts/summarize.py     # reads results/raw, writes results/summary.md and results/plots

It also writes results/thresholds/<method>.txt (one T per layer, layer 00 = 0, unquantized)
for "prepare.py --eval"; scripts/eval_accuracy.ps1 runs those and logs results/raw/accuracy.txt,
which the next run of this script adds to the summary.
"""
import re
import statistics
from collections import defaultdict
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

ROOT = Path(__file__).resolve().parent.parent
RAW, PLOTS, THRESH = ROOT / "results/raw", ROOT / "results/plots", ROOT / "results/thresholds"
METHODS = ["max", "p99.9", "p99.99", "p99.999", "p99.9999", "mse", "kl"]
STEPS = ["absmax", "histogram", "smooth", "mse", "argmin_mse", "kl", "argmin_kl", "percentile"]
PHASES = ["local_max", "max_allreduce", "local_histogram", "hist_allreduce", "smooth_percentile",
          "search", "minloc_allreduce"]
SIZE_CLASS = {**{f"{l:02d}": "16x32x32" for l in range(1, 8)},
              **{f"{l:02d}": "32x16x16" for l in range(8, 14)},
              **{f"{l:02d}": "64x8x8" for l in range(14, 19)}, "19": "64 (FC)"}


def pairs(line):
    """'name: k1 v1 k2 v2 ...' -> {k1: float(v1), ...}"""
    words = line.split(":", 1)[1].split()
    return {k: float(v) for k, v in zip(words[::2], words[1::2])}


def blocks(path):
    """Splits a log at its '== ...' header lines -> [(header, [lines])]."""
    out = []
    for line in path.read_text().splitlines():
        if line.startswith("== "):
            out.append((line[3:], []))
        elif out:
            out[-1][1].append(line)
    return out


def find(lines, prefix):
    return next((l for l in lines if l.startswith(prefix)), None)


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out) + "\n"


def plot(name, xlabel, ylabel, series, logx=True, ideal=None):
    fig, ax = plt.subplots(figsize=(6, 4))
    for label, (xs, ys) in series.items():
        ax.plot(xs, ys, marker="o", label=label)
    if ideal:
        ax.plot(ideal, ideal, "k--", linewidth=1, label="ideal")
    if logx:
        ax.set_xscale("log", base=2)
    ax.set_xlabel(xlabel)
    ax.set_ylabel(ylabel)
    ax.grid(True, alpha=0.3)
    ax.legend()
    fig.tight_layout()
    fig.savefig(PLOTS / name, dpi=150)
    plt.close(fig)


def main():
    PLOTS.mkdir(parents=True, exist_ok=True)
    THRESH.mkdir(parents=True, exist_ok=True)
    md = ["# Algorithm 1 results\n", "Generated by `scripts/summarize.py` from `results/raw`.\n"]

    # 1. P1 on every layer: checks, thresholds, per-step times, histogram variants
    p1 = {}
    for head, lines in blocks(RAW / "p1_layers.txt"):
        layer = head.split()[1]
        p1[layer] = {"result": pairs(find(lines, "result:")), "gpu": pairs(find(lines, "gpu_ms:")),
                     "cpu": pairs(find(lines, "cpu_ms:")), "hist": pairs(find(lines, "hist_ms:")),
                     "checks": [l.strip() for l in lines if "differ" in l or "expected" in l],
                     "values": int(re.search(r"(\d+) values", "\n".join(lines)).group(1))}
    layers = sorted(p1)

    bad = []
    for layer in layers:
        for c in p1[layer]["checks"]:
            # The counts that differ come before "buckets", "candidates" or " of N buckets"
            counts = re.split(r" of |buckets|candidates", c.split(":", 1)[1])[0]
            if "differ" in c and any(int(v) for v in re.findall(r"\d+", counts)):
                bad.append(f"layer {layer}: {c}")
            m = re.findall(r"bucket (\d+) \(expected (\d+)\)", c)
            bad += [f"layer {layer}: {c}" for got, exp in m if got != exp]
    md.append("## Correctness\n")
    md.append("Every P1 check against the one-thread CPU version passed on all 19 layers.\n" if not bad
              else "Failed checks:\n\n" + "\n".join(f"- {b}" for b in bad) + "\n")

    md.append("## Thresholds per layer (512 images, no smoothing)\n")
    md.append(table(["layer", "values"] + METHODS,
                    [[l, p1[l]["values"]] + [f"{p1[l]['result'][m]:.4f}" for m in METHODS] for l in layers]))
    for m in METHODS:
        (THRESH / f"{m}.txt").write_text("0\n" + "".join(f"{p1[l]['result'][m]:.6f}\n" for l in layers))

    md.append("## P1 time per step (ms, 512 images)\n")
    md.append("GPU: CUDA events, average of 10 runs after a warm-up, L2 flushed before each run. "
              "CPU: one thread, average of 3 runs.\n")
    rows = []
    for l in layers:
        g, c = p1[l]["gpu"], p1[l]["cpu"]
        rows.append([l, SIZE_CLASS[l]] + [f"{g[s]:.4f}" for s in STEPS] +
                    [f"{g['total']:.4f}", f"{c['total']:.2f}", f"{c['total'] / g['total']:.0f}x"])
    md.append(table(["layer", "shape"] + STEPS + ["GPU total", "CPU total", "speedup"], rows))

    l01 = p1["01"]
    md.append("Layer 01, per step:\n")
    md.append(table(["step", "GPU ms", "CPU ms", "speedup"],
                    [[s, f"{l01['gpu'][s]:.4f}", f"{l01['cpu'][s]:.3f}",
                      f"{l01['cpu'][s] / l01['gpu'][s]:.1f}x"] for s in STEPS]))

    md.append("## Histogram contention (GPU ms, cold L2)\n")
    rows = [[l, p1[l]["values"], f"{p1[l]['hist']['global']:.4f}", f"{p1[l]['hist']['shared']:.4f}",
             f"{p1[l]['hist']['zero_trick']:.4f}",
             f"{p1[l]['hist']['global'] / p1[l]['hist']['shared']:.1f}x"] for l in layers]
    md.append(table(["layer", "values", "global atomics", "shared", "shared + zero trick",
                     "global / shared"], rows))

    # 2. P1 vs number of blocks
    grid = [(int(h.split()[1]), pairs(find(ls, "gpu_ms:"))) for h, ls in blocks(RAW / "p1_grid.txt")]
    gs = [g for g, _ in grid]
    x_pass = [d["absmax"] + d["histogram"] for _, d in grid]
    total = [d["total"] for _, d in grid]
    cpu_x = l01["cpu"]["absmax"] + l01["cpu"]["histogram"]
    md.append("## P1 vs number of blocks (layer 01, 512 images)\n")
    md.append("Only absmax and the histogram take a grid size; the searches always launch one block "
              "per candidate. Speedup is against block count 1 and against the one-thread CPU.\n")
    md.append(table(["blocks", "threads", "absmax + histogram ms", "speedup vs 1 block",
                     "speedup vs CPU", "pipeline total ms"],
                    [[g, g * 256, f"{x:.4f}", f"{x_pass[0] / x:.1f}x", f"{cpu_x / x:.0f}x", f"{t:.4f}"]
                     for g, x, t in zip(gs, x_pass, total)]))
    plot("p1_blocks_time.png", "blocks of 256 threads", "absmax + histogram (ms)", {"P1": (gs, x_pass)})
    plot("p1_blocks_speedup.png", "blocks of 256 threads", "speedup vs 1 block",
         {"P1": (gs, [x_pass[0] / x for x in x_pass])})

    # 3. P1 vs problem size
    size = [(int(h.split()[1]), pairs(find(ls, "gpu_ms:")), pairs(find(ls, "cpu_ms:")))
            for h, ls in blocks(RAW / "p1_size.txt")]
    md.append("## P1 vs problem size (layer 01)\n")
    md.append(table(["images", "values", "GPU absmax + hist ms", "GPU total ms", "CPU total ms", "speedup"],
                    [[n, n * 16384, f"{g['absmax'] + g['histogram']:.4f}", f"{g['total']:.4f}",
                      f"{c['total']:.2f}", f"{c['total'] / g['total']:.0f}x"] for n, g, c in size]))

    # 4. P2 strong scaling
    strong = defaultdict(list)
    results_by_case = defaultdict(set)
    for head, lines in blocks(RAW / "p2_strong.txt"):
        w = head.split()
        case = f"layer {w[1]}, {w[3]} images"
        d = pairs(find(lines, "mpi_ms:"))
        strong[case].append(d)
        results_by_case[case].add(find(lines, "result:"))
    md.append("## P2 strong scaling\n")
    md.append("Each phase is timed between barriers and reported for the slowest rank, averaged over 5 runs "
              "after a warm-up. p up to 22 uses one rank per physical core; 32 and 44 use hardware threads.\n")
    same = all(len(v) == 1 for v in results_by_case.values())
    md.append(("Every p gave identical thresholds in every case.\n" if same else
               "Thresholds differ between p in: " + ", ".join(k for k, v in results_by_case.items() if len(v) > 1)
               + "\n"))
    time_series, speed_series = {}, {}
    for case, runs in strong.items():
        ps = [int(d["p"]) for d in runs]
        t1 = runs[0]["total"]
        md.append(f"### {case}\n")
        md.append(table(["p", "total ms", "computation ms", "communication ms", "search slowest / fastest",
                         "speedup", "efficiency"],
                        [[int(d["p"]), f"{d['total']:.3f}", f"{d['comp']:.3f}", f"{d['comm']:.3f}",
                          f"{d['search'] / d['search_fastest']:.2f}", f"{t1 / d['total']:.2f}x",
                          f"{t1 / d['total'] / d['p'] * 100:.0f}%"] for d in runs]))
        md.append(table(["p"] + PHASES, [[int(d["p"])] + [f"{d[ph]:.4f}" for ph in PHASES] for d in runs]))
        time_series[case] = (ps, [d["total"] for d in runs])
        speed_series[case] = (ps, [t1 / d["total"] for d in runs])
    plot("p2_strong_time.png", "MPI ranks p", "time per layer (ms)", time_series)
    plot("p2_strong_speedup.png", "MPI ranks p", "speedup T(1) / T(p)", speed_series,
         ideal=sorted({p for ps, _ in speed_series.values() for p in ps}))
    big = strong["layer 01, 4096 images"]
    plot("p2_breakdown.png", "MPI ranks p", "time (ms)",
         {"computation": ([int(d["p"]) for d in big], [d["comp"] for d in big]),
          "communication": ([int(d["p"]) for d in big], [d["comm"] for d in big])})

    # 5. P2 weak scaling
    weak = [pairs(find(ls, "mpi_ms:")) for _, ls in blocks(RAW / "p2_weak.txt")]
    md.append("## P2 weak scaling (layer 01, 64 images per rank)\n")
    md.append("Only the passes over the data (local max and histogram) have fixed work per rank; the "
              "search over 1,921 candidates is the same total work at every p, so it still shrinks as "
              "1/p. Efficiency is therefore measured on the data passes.\n")
    data = lambda d: d["local_max"] + d["local_histogram"]
    md.append(table(["p", "images", "max + histogram ms", "efficiency", "search ms", "communication ms",
                     "total ms"],
                    [[int(d["p"]), int(d["p"]) * 64, f"{data(d):.3f}", f"{data(weak[0]) / data(d) * 100:.0f}%",
                      f"{d['search']:.3f}", f"{d['comm']:.3f}", f"{d['total']:.3f}"] for d in weak]))
    plot("p2_weak_time.png", "MPI ranks p (64 images each)", "time (ms)",
         {"max + histogram": ([int(d["p"]) for d in weak], [data(d) for d in weak]),
          "search": ([int(d["p"]) for d in weak], [d["search"] for d in weak])})

    # 6. Smoothing: spread of T across 8 disjoint subsets
    runs = defaultdict(list)  # (layer, size, radius) -> [result]
    for line in (RAW / "smoothing.txt").read_text().splitlines():
        w = line.split()
        r = pairs(line[line.index("result:"):])
        runs[(w[1], int(w[3]), int(r["radius"]))].append(r)
    sizes = sorted({k[1] for k in runs})
    radii = sorted({k[2] for k in runs})
    # Layers with 8 subsets of every size; the others only have the first 512 images
    spread = sorted({k[0] for k in runs if k[1] == sizes[0]})

    def cv(layer, size, radius, method):
        ts = [r[method] for r in runs[(layer, size, radius)]]
        return statistics.pstdev(ts) / statistics.mean(ts) * 100

    md.append("## Smoothing: spread of T across 8 disjoint subsets\n")
    md.append(f"Coefficient of variation of T (std / mean, %) across the 8 subsets of each size, "
              f"averaged over layers {', '.join(spread)} (one per shape). Lower is more stable. "
              f"Percentile and max read the raw histogram, so smoothing does not change them.\n")
    for method in ["kl", "mse", "p99.99", "max"]:
        md.append(f"### {method}\n")
        md.append(table(["images"] + [f"radius {r}" for r in radii],
                        [[s] + [f"{statistics.mean(cv(l, s, r, method) for l in spread):.2f}" for r in radii]
                         for s in sizes]))
        md.append(table(["layer", "images"] + [f"radius {r}" for r in radii],
                        [[l, s] + [f"{cv(l, s, r, method):.2f}" for r in radii] for l in spread for s in sizes]))
    md.append("### T at 512 images (the first 512), by radius\n")
    md.append(table(["layer"] + [f"{m} r{r}" for m in ["kl", "mse"] for r in radii],
                    [[l] + [f"{runs[(l, 512, r)][0][m]:.4f}" for m in ["kl", "mse"] for r in radii] for l in layers]))
    for method in ["kl", "mse"]:
        plot(f"smoothing_{method}.png", "calibration images", f"{method.upper()} spread of T (CV %)",
             {f"radius {r}": (sizes, [statistics.mean(cv(l, s, r, method) for l in spread) for s in sizes])
              for r in radii})
    # Smoothed thresholds at 512 images for the accuracy runs. Subset 0 is the first 512 images,
    # the same ones as the unsmoothed run above.
    for method in ["kl", "mse"]:
        for r in radii[1:]:
            (THRESH / f"{method}_r{r}.txt").write_text(
                "0\n" + "".join(f"{runs[(l, 512, r)][0][method]:.6f}\n" for l in layers))

    # 7. Accuracy, once scripts/eval_accuracy.ps1 has run
    acc_file = RAW / "accuracy.txt"
    if acc_file.exists():
        acc = [l.split() for l in acc_file.read_text().splitlines() if l.strip()]
        md.append("## Accuracy with INT8 activations (CIFAR-10 test set, 10,000 images)\n")
        md.append("FP32 baseline: 91.73%. Every layer's input except layer 00 (the image) is quantized "
                  "with its own T.\n")
        md.append(table(["thresholds", "accuracy", "change vs FP32"],
                        [[name, f"{float(a):.2f}%", f"{float(a) - 91.73:+.2f}"] for name, a in acc]))

    (ROOT / "results/summary.md").write_text("\n".join(md))
    print("wrote results/summary.md, results/plots, results/thresholds")


main()
